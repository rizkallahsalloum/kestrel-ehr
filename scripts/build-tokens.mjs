// Converts the Figma "Design Tokens" export into CSS custom properties.
// Only semantic tokens are emitted (as --k-semantic-*); primitives are
// resolved into them. Usage: node scripts/build-tokens.mjs [--input file] [--output file]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const REFERENCE = /^\{([^}]+)\}$/;

/** Flattens the nested token tree into a map of dot paths to { type, value }. */
export function flattenTokens(tree, prefix = [], out = new Map()) {
  for (const [key, node] of Object.entries(tree)) {
    if (key === "extensions" || key === "description" || node === null || typeof node !== "object") continue;
    const path = [...prefix, key];
    if ("value" in node && "type" in node) {
      out.set(path.join("."), { type: node.type, value: node.value });
    } else {
      flattenTokens(node, path, out);
    }
  }
  return out;
}

/** Follows {references} until a literal value is found. Returns undefined when unresolvable. */
export function resolveToken(path, tokens, seen = new Set()) {
  if (seen.has(path)) return undefined;
  seen.add(path);
  const token = tokens.get(path);
  if (!token) return undefined;
  if (typeof token.value === "string") {
    const match = REFERENCE.exec(token.value.trim());
    if (match) {
      const target = resolveToken(match[1], tokens, seen);
      return target && { type: token.type === "color" || target.type === "color" ? "color" : target.type, value: target.value };
    }
  }
  return token;
}

const FONT_WEIGHTS = { thin: 100, extralight: 200, light: 300, regular: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };

/** Formats a resolved token. `path` is the semantic path, used for unitless and named values. */
export function toCssValue(token, path = "") {
  const { type, value } = token;
  if (type === "color" && typeof value === "string") {
    const hex = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(value.trim());
    if (hex) return hex[2] === undefined || hex[2].toLowerCase() === "ff" ? `#${hex[1].toLowerCase()}` : value.toLowerCase();
    return value;
  }
  if (path.includes(".opacity.") && typeof value === "number") return String(value);
  if (type === "dimension" && typeof value === "number") return value === 0 ? "0" : `${value}px`;
  if (path.includes(".text-weight.") && typeof value === "string") {
    const weight = FONT_WEIGHTS[value.toLowerCase().replace(/[\s-]/g, "")];
    if (weight) return String(weight);
  }
  if (path.includes(".text-family.") && typeof value === "string" && /\s/.test(value)) return `"${value}"`;
  return String(value);
}

export function cssVarName(path) {
  return `--k-${path.replace(/\./g, "-")}`;
}

/** Builds the stylesheet. Unresolvable tokens are listed rather than guessed. */
export function buildCss(tokens, source) {
  const lines = [];
  const unresolved = [];
  for (const path of [...tokens.keys()].filter((p) => p.startsWith("semantic.")).sort()) {
    const token = resolveToken(path, tokens);
    if (!token) {
      unresolved.push(path);
      continue;
    }
    lines.push(`  ${cssVarName(path)}: ${toCssValue(token, path)};`);
  }
  const header = [
    `/* Generated by scripts/build-tokens.mjs from ${source}. Do not edit by hand. */`,
    ...(unresolved.length
      ? [`/* Unresolved (missing from the export, theme falls back to defaults): ${unresolved.join(", ")} */`]
      : []),
  ];
  return { css: `${header.join("\n")}\n:root {\n${lines.join("\n")}\n}\n`, unresolved, count: lines.length };
}

function main() {
  const args = process.argv.slice(2);
  const arg = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
  const input = arg("--input", "design-reference/design-tokens.tokens.json");
  const output = arg("--output", "src/styles/tokens.css");

  let tree;
  try {
    tree = JSON.parse(readFileSync(resolve(input), "utf8"));
  } catch (error) {
    console.error(`Could not parse ${input}: ${error.message}`);
    console.error("Re-export the complete token file from Figma and run `pnpm tokens:build` again.");
    process.exit(1);
  }

  const { css, unresolved, count } = buildCss(flattenTokens(tree), input.replace(/\\/g, "/"));
  writeFileSync(resolve(output), css);
  console.log(`Wrote ${count} semantic tokens to ${output}.`);
  if (unresolved.length) console.warn(`${unresolved.length} token(s) could not be resolved.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
